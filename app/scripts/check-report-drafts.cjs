const fs = require('node:fs');
const assert = require('node:assert/strict');
const esbuild = require('esbuild');
const source = fs.readFileSync('app/src/components/ReportRecordReview.tsx', 'utf8');
const code = esbuild.transformSync(source, {loader: 'tsx', format: 'cjs'}).code;
const compiled = {exports: {}};
new Function('require', 'module', 'exports', code)(name => name.includes('careApi') ? {} : require(name), compiled, compiled.exports);
const suggest = compiled.exports.reportSuggestions;
const prescription = suggest('Report date: 2026-01-01\nDiagnosis: Example condition\nRx\nTab Example 5 mg, instructions as printed\nWeight: 18 kg\nHeight: 110 cm');
assert.equal(prescription.date, '2026-01-01');
assert.equal(prescription.diagnosis, 'Diagnosis: Example condition');
assert(prescription.prescription.includes('Tab Example 5 mg'));
assert.equal(prescription.weight, '18');
assert.equal(prescription.height, '110');
const lab = suggest('DOB: 2020-01-01\nGlucose: 90 mg/dL\nNo diagnosis supplied');
assert.equal(lab.prescription, '');
assert.equal(lab.date, '');
assert.equal(suggest('Date: 2026-99-99').date, '');
assert.equal(suggest('No readable measurements').weight, '');
assert.equal(suggest('\u0935\u091c\u0928: 18 kg').weight, '18');
console.log('PASS report drafts: exact medicine text, measurements, explicit report date, no invented values or lab-unit prescriptions.');
