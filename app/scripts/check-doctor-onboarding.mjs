import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';

const browser = await chromium.launch({channel:'msedge'});
const page = await browser.newPage({viewport:{width:1366,height:1000}});
const requests = [];
const user = {id:'doctor-test',public_id:'D_TEST',full_name:'Dr Test Doctor',email:'doctor-test@example.com',phone_number:'+919876543210',role:'DOCTOR',approval_status:'PROFILE_REQUIRED'};
const setup = {requires_profile_setup:true,setup_token:'test-setup-token',user,doctor:{}};
await page.route('**/api/v1/**', async route => {
  const path = new URL(route.request().url()).pathname;
  const body = route.request().postDataJSON();
  requests.push({path,body});
  let json;
  if(path.endsWith('/register')) json={challenge_token:'test-challenge',resend_after:60,email_status:'sent'};
  else if(path.endsWith('/verify-email') || path.endsWith('/login')) json=setup;
  else if(path.endsWith('/setup-profile')) json={user:{...user,approval_status:'PENDING_APPROVAL'},message:'Your profile is under review.'};
  else return route.fulfill({status:401,json:{error:{code:'session_revoked',message:'No session'}}});
  return route.fulfill({status:202,json});
});
try {
  await page.goto('http://127.0.0.1:5173/doctor/signup');
  await page.locator('input[name=name]').fill(user.full_name);
  await page.locator('input[name=phone]').fill('9876543210');
  await page.locator('input[name=email]').fill(user.email);
  await page.locator('input[name=password]').fill('ExamplePassword8!');
  await page.locator('input[name=confirm_password]').fill('ExamplePassword8!');
  assert.equal(await page.locator('input[name=registration]').count(),0);
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByRole('heading',{name:'Verify OTP',exact:true}).waitFor();
  const registration = requests.find(r=>r.path.endsWith('/register')).body;
  assert.deepEqual(Object.keys(registration).sort(),['confirm_password','email','full_name','mobile_number','password']);
  await page.getByRole('textbox',{name:'OTP digit 1',exact:true}).fill('123456');
  await page.getByRole('button',{name:'Verify OTP',exact:true}).click();
  await page.getByRole('heading',{name:'Setup Doctor Profile',exact:true}).waitFor();
  assert.equal(await page.getByLabel('Full name',{exact:true}).inputValue(),user.full_name);
  assert.equal(await page.getByLabel('Email',{exact:true}).inputValue(),user.email);
  await page.locator('input[name=qualification]').fill('MBBS');
  await page.locator('input[name=registration]').fill('TEST-123');
  await page.locator('input[name=council]').fill('Example Council');
  await page.locator('textarea[name=address]').fill('Doctor Street, Delhi 110001');
  await page.locator('textarea[name=clinicAddress]').fill('Clinic Road, Delhi 110002');
  await page.locator('input[name=years_of_experience]').fill('0');
  await mkdir('.test-data',{recursive:true});
  await page.screenshot({path:'.test-data/doctor-profile-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'.test-data/doctor-profile-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Submit for Approval',exact:true}).click();
  await page.getByRole('heading',{name:'Your profile is under review',exact:true}).waitFor();
  const submitted = requests.find(r=>r.path.endsWith('/setup-profile')).body;
  assert.equal(submitted.years_of_experience,0);
  assert.equal(submitted.clinic_address,'Clinic Road, Delhi 110002');
  assert.equal(submitted.specialization,null);
  assert.equal(submitted.nmr_id,null);
  assert.equal(requests.filter(r=>r.path.endsWith('/setup-profile')).length,1);
  await page.goto('http://127.0.0.1:5173/doctor/login');
  await page.locator('input[name=email]').fill(user.email);
  await page.locator('input[name=password]').fill('ExamplePassword8!');
  await page.getByRole('button',{name:'Login',exact:true}).click();
  await page.getByRole('heading',{name:'Setup Doctor Profile',exact:true}).waitFor();
  console.log('PASS basic signup → OTP → profile setup → submit for review; resume on login; responsive layout.');
} finally { await browser.close(); }
